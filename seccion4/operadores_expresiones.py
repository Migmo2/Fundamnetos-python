# Operadores y expresiones en Python

numero_a = 10
numero_b = 5

resultado = (numero_a + numero_b) * 2

print("Resultado de la expresión:", resultado)

# Operadores de comparación

print("¿A es mayor que B?", numero_a > numero_b)
print("¿A es menor que B?", numero_a < numero_b)
print("¿A es igual a B?", numero_a == numero_b)
print("¿A es diferente de B?", numero_a != numero_b)

# Operadores lógicos

tiene_usuario = True
tiene_permiso = False

print("Acceso permitido:", tiene_usuario and tiene_permiso)
print("Tiene alguna condición:", tiene_usuario or tiene_permiso)
