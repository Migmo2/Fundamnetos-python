# Ejemplo de literales de cadenas en Python

nombre = "Gilmaro"
ciudad = "Colombia"

mensaje = "Estoy aprendiendo fundamentos de Python"

print("Nombre:", nombre)
print("Ciudad:", ciudad)
print(mensaje)

# Diferentes formas de escribir cadenas

cadena_simple = 'Python es sencillo'
cadena_doble = "Python es poderoso"

print(cadena_simple)
print(cadena_doble)
